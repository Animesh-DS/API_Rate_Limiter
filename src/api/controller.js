const queues = require('../config/queues');
const logger = require('../utils/logger');

const processTask = async (req, res) => {
  const { userTier, userIdentifier } = req;
  const correlationId = req.id; // Generated by Pino in the Gateway
  
  const payload = req.body;
  
  // Dynamically select the correct queue: premiumQueue, standardQueue, or freeQueue
  const queue = queues[`${userTier}Queue`];
  
  if (!queue) {
    logger.error({ tier: userTier }, 'Queue not found for tier');
    return res.status(500).json({ error: 'Internal Server Error' });
  }

  try {
    // Add the task to BullMQ
    const job = await queue.add('heavy-task', {
      payload,
      userIdentifier,
      userTier,
      correlationId
    }, {
      jobId: correlationId // Use the correlation ID as the Job ID
    });

    logger.info({ jobId: job.id, tier: userTier, queue: queue.name }, 'Job successfully queued');
    
    // Return 202 Accepted IMMEDIATELY. The main thread is now free.
    res.status(202).json({
      message: 'Request accepted. Processing in background.',
      jobId: job.id,
      tier: userTier
    });
  } catch (error) {
    logger.error({ err: error, correlationId }, 'Failed to queue job');
    res.status(503).json({ error: 'Service Unavailable' });
  }
};

module.exports = {
  processTask
};